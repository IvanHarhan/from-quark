import type { SourceId } from './types';

/** log10(P / bar) = A − B / (T + C), valid for tMin ≤ T ≤ tMax (K). NIST WebBook form. */
export interface Antoine {
  A: number;
  B: number;
  C: number;
  tMin: number;
  tMax: number;
}

export type Viscosity =
  /** μ = A · 10^(B / (T − C)), Pa·s */
  | { model: 'vogel'; A: number; B: number; C: number }
  /** log10(μ / mPa·s) = a1 + a2 / T */
  | { model: 'log10'; a1: number; a2: number }
  /** One value at a reference temperature, no T dependence (simplification). */
  | { model: 'const'; value: number; atT: number };

/**
 * Mechanical behaviour of the solid in the simulator. Real moduli (10–200 GPa) would need ~10⁵ substeps
 * per second, so stiffness is scaled to the artificial sound speed and plasticity is set by a scaled
 * yield strain: deformation shapes are qualitative, forces are not real.
 */
export interface SolidModel {
  /** Strain beyond which the solid flows plastically (scaled); null = elastic only (ice). */
  yieldStrain: number | null;
  poisson: number;
}

/**
 * How a phase looks: 'clear' liquids/solids refract and tint light passing through, 'metal' reflects the
 * room (tinted by its colour), 'matte' scatters (salt crystals, frost).
 */
export interface Look {
  kind: 'clear' | 'metal' | 'matte';
  color: string;
  /** clear: how strongly the colour absorbs per cm of thickness (0 = colourless). */
  absorb?: number;
  roughness?: number;
}

export interface Substance {
  id: string;
  ru: string;
  en: string;
  formula: string;
  /** Structure for the molecular zoom (Kekulé SMILES); omitted for metals and ionic crystals. */
  smiles?: string;
  /** Short caveat shown in the UI (sublimation, decomposition, ...). */
  note?: { ru: string; en: string };
  /** g/mol */
  molarMass: number;
  /** K at 1 atm */
  tm: number;
  /** K at 1 atm */
  tb: number;
  /** kg/m³ */
  rhoSolid: number;
  rhoLiquid: number;
  /** J/(kg·K) */
  cpSolid: number;
  cpLiquid: number;
  /** J/kg */
  lf: number;
  lv: number;
  /** W/(m·K) */
  kSolid: number;
  kLiquid: number;
  /** Volumetric thermal expansion of the liquid, 1/K (drives natural convection). */
  betaLiquid: number;
  viscosity: Viscosity;
  antoine?: Antoine[];
  triple?: { T: number; P: number };
  critical?: { T: number; P: number };
  solid: SolidModel;
  /** Particle colours (used for the particle fallback and the micro views). */
  colors: { solid: string; liquid: string };
  look: { solid: Look; liquid: Look };
  /** Source of each numeric field; fields not listed come from `default`. */
  sources: { default: SourceId } & Partial<Record<keyof Substance, SourceId>>;
}

